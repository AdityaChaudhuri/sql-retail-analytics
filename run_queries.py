"""
Runs sql/02_data_quality.sql and sql/04_analysis.sql against retail.db
(rebuilding the cleaning views from sql/03_clean_views.sql first) and
writes every result as a markdown table into results/results.md.

Run:  python run_queries.py
"""
import os
import re
import sqlite3

ROOT = os.path.dirname(os.path.abspath(__file__))
DB_PATH = os.path.join(ROOT, "retail.db")
SQL_DIR = os.path.join(ROOT, "sql")
RESULTS_PATH = os.path.join(ROOT, "results", "results.md")


def split_statements(sql_text):
    """Split into (title, statement) pairs, title from the nearest '-- @title'."""
    statements = []
    title = None
    buf = []
    for line in sql_text.splitlines():
        stripped = line.strip()
        m = re.match(r"--\s*@title\s+(.*)", stripped)
        if m:
            title = m.group(1).strip()
            continue
        buf.append(line)
        if stripped.endswith(";"):
            stmt = "\n".join(buf).strip()
            if stmt:
                statements.append((title, stmt))
            buf = []
            title = None
    tail = "\n".join(buf).strip()
    if tail:
        statements.append((title, tail))
    return statements


def run_file_capturing_results(conn, path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    sections = []
    for title, stmt in split_statements(text):
        if title is None:
            continue
        cur = conn.execute(stmt)
        cols = [d[0] for d in cur.description]
        rows = cur.fetchall()
        sections.append((title, cols, rows))
    return sections


def to_markdown_table(cols, rows):
    if not rows:
        return "_no rows_\n"
    header = "| " + " | ".join(cols) + " |"
    sep = "| " + " | ".join("---" for _ in cols) + " |"
    lines = [header, sep]
    for row in rows:
        cells = ["" if v is None else str(v) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main():
    conn = sqlite3.connect(DB_PATH)

    # rebuild views fresh each run
    with open(os.path.join(SQL_DIR, "03_clean_views.sql"), encoding="utf-8") as f:
        conn.executescript(f.read())

    dq_sections = run_file_capturing_results(conn, os.path.join(SQL_DIR, "02_data_quality.sql"))
    analysis_sections = run_file_capturing_results(conn, os.path.join(SQL_DIR, "04_analysis.sql"))

    out = ["# Harbour & Home — Query Results\n",
           "Generated by `run_queries.py` against `retail.db`.\n",
           "## Data Quality Checks\n"]
    for title, cols, rows in dq_sections:
        out.append(f"### {title}\n")
        out.append(to_markdown_table(cols, rows))
        out.append("")

    out.append("## Business Questions\n")
    for title, cols, rows in analysis_sections:
        out.append(f"### {title}\n")
        out.append(to_markdown_table(cols, rows))
        out.append("")

    os.makedirs(os.path.dirname(RESULTS_PATH), exist_ok=True)
    with open(RESULTS_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(out))

    conn.close()
    print(f"wrote {RESULTS_PATH}")


if __name__ == "__main__":
    main()
