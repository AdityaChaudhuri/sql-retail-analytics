"""
Runs sql/02_data_quality.sql and sql/04_analysis.sql against retail.db
(rebuilding the cleaning views from sql/03_clean_views.sql first) and
writes every result as a markdown table into results/results.md.

Run:  python run_queries.py
"""
import os
import re
import sqlite3

ROOT = os.path.dirname(os.path.abspath(__file__))
DB_PATH = os.path.join(ROOT, "retail.db")
SQL_DIR = os.path.join(ROOT, "sql")
RESULTS_PATH = os.path.join(ROOT, "results", "results.md")


def split_statements(sql_text):
    """Split into (section, title, statement) tuples. Title comes from the
    nearest '-- @title'; section from the nearest '-- @section' (carries
    across multiple titles until a new one is seen)."""
    statements = []
    section = None
    title = None
    buf = []
    for line in sql_text.splitlines():
        stripped = line.strip()
        m_section = re.match(r"--\s*@section\s+(.*)", stripped)
        if m_section:
            section = m_section.group(1).strip()
            continue
        m_title = re.match(r"--\s*@title\s+(.*)", stripped)
        if m_title:
            title = m_title.group(1).strip()
            continue
        buf.append(line)
        if stripped.endswith(";"):
            stmt = "\n".join(buf).strip()
            if stmt:
                statements.append((section, title, stmt))
            buf = []
            title = None
    tail = "\n".join(buf).strip()
    if tail:
        statements.append((section, title, tail))
    return statements


def run_file_capturing_results(conn, path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    results = []
    for section, title, stmt in split_statements(text):
        if title is None:
            continue
        cur = conn.execute(stmt)
        cols = [d[0] for d in cur.description]
        rows = cur.fetchall()
        results.append((section, title, cols, rows))
    return results


def to_markdown_table(cols, rows):
    if not rows:
        return "_no rows_\n"
    header = "| " + " | ".join(cols) + " |"
    sep = "| " + " | ".join("---" for _ in cols) + " |"
    lines = [header, sep]
    for row in rows:
        cells = ["" if v is None else str(v) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def append_group(out, heading, results):
    out.append(f"## {heading}\n")
    seen_section = None
    for section, title, cols, rows in results:
        if section != seen_section:
            out.append(f"### {section}\n")
            seen_section = section
        out.append(f"#### {title}\n")
        out.append(to_markdown_table(cols, rows))
        out.append("")


def main():
    conn = sqlite3.connect(DB_PATH)

    # rebuild views fresh each run
    with open(os.path.join(SQL_DIR, "03_clean_views.sql"), encoding="utf-8") as f:
        conn.executescript(f.read())

    dq_results = run_file_capturing_results(conn, os.path.join(SQL_DIR, "02_data_quality.sql"))
    analysis_results = run_file_capturing_results(conn, os.path.join(SQL_DIR, "04_analysis.sql"))

    out = ["# Harbour & Home — Query Results\n",
           "Generated by `run_queries.py` against `retail.db`.\n"]
    append_group(out, "Data Profiling", dq_results)
    append_group(out, "Findings", analysis_results)

    os.makedirs(os.path.dirname(RESULTS_PATH), exist_ok=True)
    with open(RESULTS_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(out))

    conn.close()
    print(f"wrote {RESULTS_PATH}")


if __name__ == "__main__":
    main()
